    fn install_state(&self) -> (bool, Option<String>) {
        if self.scanning || self.job.is_some() {
            return (false, Some("Идёт операция…".into()));
        }
        if self.selected_package().is_none() {
            return (false, Some("Нет пакета в кэше".into()));
        }
        match &self.scan {
            None => (false, Some("Сначала проверьте папку игры".into())),
            Some(scan) => {
                if scan.running.len() > 0 {
                    return (false, Some("Закройте игру".into()));
                }
                if !scan.writable {
                    return (false, Some("Нужны права администратора".into()));
                }
                if scan.exes.is_empty() {
                    return (false, Some("EXE игры не найден".into()));
                }
                let mut note = None;
                if !self.gpu.is_nvidia {
                    note = Some("Нужна видеокарта NVIDIA RTX".into());
                } else if !self.gpu.driver_ok() {
                    note = Some(format!("Драйвер младше R{}", dlssgm::model::DRIVER_FLOOR));
                } else if scan.bad_count() > 0 {
                    note = Some("Есть критичные замечания".into());
                }
                (true, note)
            }
        }
    }

