    /// One auto-detected game card; returns true when clicked.
    fn game_tile(&mut self, ui: &mut egui::Ui, idx: usize) -> bool {
        let Some(game) = self.games.get(idx) else {
            return false;
        };
        let name = game.name.clone();
        let dir = game.dir.clone();
        let drive = game.drive();
        let source = if drive.is_empty() {
            game.source.clone()
        } else {
            format!("{} · {}", game.source, drive)
        };
        let dlssg = game.dlssg;
        let has_dlss = game.has_dlss;
        let installed = game.installed_version.clone();
        let icon_path = game.icon.clone();
        let active = dlssgm::config::same_path(&dir, &PathBuf::from(self.game_dir.trim()));
        let tex = icon_path.as_deref().and_then(|p| self.icon_texture(p));

        let size = Vec2::new(212.0, 92.0);
        let (rect, resp) = ui.allocate_exact_size(size, egui::Sense::click());
        let painter = ui.painter();
        let bg = if active {
            ACCENT_DARK
        } else if resp.hovered() {
            Color32::from_rgb(34, 41, 55)
        } else {
            PANEL_2
        };
        painter.rect_filled(rect, Rounding::same(10.0), bg);
        painter.rect_stroke(
            rect,
            Rounding::same(10.0),
            Stroke::new(
                1.0_f32,
                if active {
                    ACCENT.gamma_multiply(0.8)
                } else {
                    BORDER
                },
            ),
        );

        let icon_rect = egui::Rect::from_min_size(rect.min + Vec2::new(10.0, 12.0), Vec2::splat(44.0));
        match &tex {
            Some(handle) => {
                painter.image(
                    handle.id(),
                    icon_rect,
                    egui::Rect::from_min_max(egui::pos2(0.0, 0.0), egui::pos2(1.0, 1.0)),
                    Color32::WHITE,
                );
            }
            None => {
                let color = avatar_color(&name);
                painter.rect_filled(icon_rect, Rounding::same(9.0), color.gamma_multiply(0.22));
                let letter = name
                    .chars()
                    .find(|c| !c.is_whitespace())
                    .map(|c| c.to_uppercase().to_string())
                    .unwrap_or_else(|| "?".into());
                painter.text(
                    icon_rect.center(),
                    egui::Align2::CENTER_CENTER,
                    letter,
                    egui::FontId::proportional(20.0),
                    color,
                );
            }
        }

        let text_x = icon_rect.right() + 10.0;
        painter.text(
            egui::pos2(text_x, rect.top() + 12.0),
            egui::Align2::LEFT_TOP,
            clip_text(&name, 21),
            egui::FontId::proportional(13.5),
            TEXT,
        );
        painter.text(
            egui::pos2(text_x, rect.top() + 32.0),
            egui::Align2::LEFT_TOP,
            clip_text(&source, 25),
            egui::FontId::proportional(11.0),
            MUTED,
        );
        let (tag, tag_color) = if dlssg {
            (i18n::t("DLSS Frame Generation"), ACCENT)
        } else if has_dlss {
            (i18n::t("DLSS без FG"), BLUE)
        } else {
            (i18n::t("DLSS не найден"), YELLOW)
        };
        painter.text(
            egui::pos2(text_x, rect.top() + 50.0),
            egui::Align2::LEFT_TOP,
            tag,
            egui::FontId::proportional(11.0),
            tag_color,
        );
        if let Some(version) = installed {
            painter.text(
                egui::pos2(text_x, rect.top() + 68.0),
                egui::Align2::LEFT_TOP,
                clip_text(&i18n::tr(&format!("мод {version}")), 20),
                egui::FontId::proportional(11.0),
                MUTED,
            );
        }
        if resp.hovered() {
            ui.ctx().set_cursor_icon(egui::CursorIcon::PointingHand);
        }
        resp.clicked()
    }

