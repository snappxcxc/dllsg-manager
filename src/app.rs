    fn toasts(&mut self, ui: &mut egui::Ui) {
        self.toasts.retain(|(t, _, _)| t.elapsed() < Duration::from_secs(6));
        let height = 46.0 * self.toasts.len() as f32 + 16.0;
        if self.toasts.is_empty() {
            return;
        }
        let rect = egui::Rect::from_min_size(
            ui.max_rect().right_top() - Vec2::new(430.0, height + 8.0),
            Vec2::new(410.0, height),
        );
        let mut area = ui.new_child(
            egui::UiBuilder::new()
                .max_rect(rect)
                .layout(egui::Layout::top_down(egui::Align::Max)),
        );
        let toasts = self.toasts.clone();
        for (t, text, color) in toasts.iter().rev() {
            let alpha = ((6.0 - t.elapsed().as_secs_f32()) / 1.5).clamp(0.0, 1.0);
            egui::Frame::none()
                .fill(Color32::from_rgb(24, 29, 39).gamma_multiply(alpha.max(0.2)))
                .rounding(Rounding::same(10.0))
                .stroke(Stroke::new(1.0, color.gamma_multiply(alpha.max(0.2))))
                .inner_margin(egui::Margin::symmetric(14.0, 10.0))
                .show(&mut area, |ui| {
                    ui.set_max_width(380.0);
                    ui.horizontal_wrapped(|ui| {
                        ui.label(rt(text).size(12.5).color(TEXT.gamma_multiply(alpha.max(0.2))));
                    });
                });
            area.add_space(6.0);
        }
    }
