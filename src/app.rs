    fn update_all(&mut self) {
        let Some(pkg) = self.selected_package().cloned() else {
            return;
        };
        let installs = self.cfg.installs.clone();
        if installs.is_empty() {
            return;
        }
        self.toast(
            format!("Обновление {} папок до {}", installs.len(), pkg.version),
            BLUE,
        );
        self.spawn("Обновление всех установок", move |tx, _c| {
            let mut ok = Vec::new();
            let mut fail = Vec::new();
            let total = installs.len() as f32;
            for (i, inst) in installs.into_iter().enumerate() {
                let proxy = inst.proxy.clone();
                let opts = installer::InstallOpts {
                    dir: &inst.path,
                    exe: &inst.exe,
                    pkg: &pkg,
                    proxy: &proxy,
                    remove_extra_proxies: true,
                };
                let prefix = format!("{}: ", inst.path.display());
                match installer::install(
                    opts,
                    &mut |p, m| {
                        let _ = tx.send(Msg::Progress(
                            (i as f32 + p) / total,
                            format!("{prefix}{m}"),
                        ));
                    },
                    &mut |l| {
                        let _ = tx.send(Msg::Log(format!("{prefix}{l}")));
                    },
                ) {
                    Ok(rec) => ok.push(rec),
                    Err(e) => fail.push(format!("{}: {e}", inst.path.display())),
                }
            }
            let mut text = format!("Обновлено папок: {}", ok.len());
            if !fail.is_empty() {
                text = format!("{text}. Ошибки: {}", fail.join("; "));
            }
            let _ = tx.send(Msg::UpdateResult {
                ok: fail.is_empty(),
                text,
            });
            let _ = tx.send(Msg::Packages(packages::list_packages()));
            let _ = tx.send(Msg::Info(format!("Обновление завершено: {}", ok.len())));
        });
        // Persist new versions once the job is done is handled by re-scan below.
        let mut cfg = self.cfg.clone();
        cfg.auto_apply = true;
        let _ = cfg.save();
    }

